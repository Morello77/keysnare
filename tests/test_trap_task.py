import xml.etree.ElementTree as ET  # noqa: S405 - parses only XML generated by our own code
from pathlib import Path

from keysnare.trap.task import TASK_NAME, build_task_xml, relay_query

NS = {"t": "http://schemas.microsoft.com/windows/2004/02/mit/task"}
HANDLER = Path("C:/Users/dev/.venv/Scripts/pythonw.exe")
XML = build_task_xml(HANDLER, "S-1-5-21-1-2-3-1001")


def task() -> ET.Element:
    return ET.fromstring(XML)  # noqa: S314 - our own generated XML


def test_task_name_is_in_the_keysnare_folder() -> None:
    assert TASK_NAME == "\\KeySnare\\DecoyRead"


def test_task_never_runs_elevated() -> None:
    principal = task().find("t:Principals/t:Principal", NS)

    assert principal is not None
    assert principal.findtext("t:RunLevel", namespaces=NS) == "LeastPrivilege"
    assert principal.findtext("t:LogonType", namespaces=NS) == "InteractiveToken"
    assert principal.findtext("t:UserId", namespaces=NS) == "S-1-5-21-1-2-3-1001"
    assert "HighestAvailable" not in XML


def test_trigger_is_the_relay_event_in_the_application_log() -> None:
    subscription = task().findtext("t:Triggers/t:EventTrigger/t:Subscription", namespaces=NS)

    assert subscription == relay_query()
    assert '<Select Path="Application">' in subscription
    assert "Provider[@Name='KeySnare'] and EventID=100" in subscription
    assert "Security" not in subscription


def test_handler_receives_no_event_fields_on_its_command_line() -> None:
    action = task().find("t:Actions/t:Exec", NS)

    assert action is not None
    assert action.findtext("t:Command", namespaces=NS) == str(HANDLER)
    assert action.findtext("t:Arguments", namespaces=NS) == "-m keysnare trap alert"
    assert "ValueQueries" not in XML
